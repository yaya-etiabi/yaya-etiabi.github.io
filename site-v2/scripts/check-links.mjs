import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, extname, isAbsolute, join, relative, resolve } from 'node:path';

const root = resolve('dist');
const base = (process.env.BASE_PATH || '/').replace(/\/$/, '');
let linksChecked = 0;
let anchorsChecked = 0;
const failures = [];
const pageIds = new Map();

function walk(folder) {
  return readdirSync(folder, { withFileTypes: true }).flatMap((item) => {
    const path = join(folder, item.name);
    return item.isDirectory() ? walk(path) : [path];
  });
}

function getIds(page) {
  if (!pageIds.has(page)) {
    const html = readFileSync(page, 'utf8');
    const ids = new Set([...html.matchAll(/\b(?:id|name)="([^"]+)"/g)].map((match) => match[1]));
    pageIds.set(page, ids);
  }
  return pageIds.get(page);
}

function check(url, file) {
  if (!url || /^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(url)) return;
  const separator = url.indexOf('#');
  const location = (separator === -1 ? url : url.slice(0, separator)).split('?')[0];
  const fragment = separator === -1 ? '' : url.slice(separator + 1);

  let path = location;
  if (!location) {
    path = file;
  } else if (location.startsWith('/')) {
    if (base && location !== base && !location.startsWith(base + '/')) {
      failures.push(file + ': missing preview base prefix: ' + url);
      return;
    }
    path = resolve(root, decodeURIComponent(base ? location.slice(base.length) || '/' : location).replace(/^\/+/, ''));
  } else {
    path = resolve(dirname(file), decodeURIComponent(location));
  }

  if (path === root || (existsSync(path) && !extname(path))) {
    path = join(path, 'index.html');
  } else if (!extname(path)) {
    path = join(path, 'index.html');
  }

  const outside = relative(root, path);
  if (outside.startsWith('..') || isAbsolute(outside)) {
    failures.push(file + ': link leaves dist/: ' + url);
    return;
  }

  linksChecked++;
  if (!existsSync(path)) {
    failures.push(file + ': missing target for ' + url);
    return;
  }

  if (fragment && path.endsWith('.html')) {
    const anchor = decodeURIComponent(fragment);
    anchorsChecked++;
    if (anchor !== 'top' && !getIds(path).has(anchor)) {
      failures.push(file + ': missing anchor #' + anchor + ' in ' + path);
    }
  }
}

if (!existsSync(root)) {
  console.error('No dist/ output. Run npm run build first.');
  process.exit(1);
}

const htmlFiles = walk(root).filter((file) => file.endsWith('.html'));
for (const file of htmlFiles) {
  const html = readFileSync(file, 'utf8');
  // HTML generated by Astro consistently quotes href, src and srcset attributes.
  for (const match of html.matchAll(/(?:href|src)="([^"]+)"/g)) {
    check(match[1], file);
  }
  for (const match of html.matchAll(/\bsrcset="([^"]+)"/g)) {
    for (const candidate of match[1].split(',')) {
      check(candidate.trim().split(/\s+/)[0], file);
    }
  }
}
if (failures.length) {
  console.error(failures.join('\n'));
  console.error('Validation failed: ' + failures.length + ' unresolved local links/assets/anchors.');
  process.exit(1);
}
console.log('OK: ' + htmlFiles.length + ' HTML files; ' + linksChecked + ' local links/assets and ' + anchorsChecked + ' anchors verified.');
